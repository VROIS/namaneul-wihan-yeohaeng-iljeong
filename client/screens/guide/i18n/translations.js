export function normalizeLang(lang) {
  return lang === "zh" ? "zh-CN" : lang;
}

// ⚠️ 수정금지(승인필요): 번역 함수
export function t(key, lang = "ko") {
  const normalized = normalizeLang(lang);
  return translations[normalized]?.[key] || translations.ko[key] || key;
}

// ⚠️ 수정금지(승인필요) 2026-08-24 사장님 승인 = 생년월일 수집 정책 **토글 1벌**(화면·서버 공용 SSOT).
// ───────────────────────────────────────────────────────────────────────────
// 【왜 토글인가】 2026-08-24 애플 심사 리젝(지침 5.1.1(v) 개인정보) = "앱 핵심 기능과 직접 관련 없는
//   개인정보(생일)를 **필수로** 요구하지 말 것". 그래서 지금은 'optional' 로 두고 심사를 통과시키되,
//   기존 필수 로직은 지우지 않고 이 스위치의 반대편으로 보존한다 = 애플에 수집 사유를 설명하고
//   대안 회신을 받은 뒤 결론이 나면 그때 한쪽을 삭제한다(§19 = 결론 확정 시 옛것 완전삭제).
//
// 【두 위치의 뜻】
//   'required' = 옛 동작 = 생년월일을 넣어야 로그인 버튼이 진행된다(2026-07-25 SSOT).
//   'optional' = 현재   = 비워 두어도 소셜 3종 로그인이 끝까지 성공한다. 넣었을 때만 성인 여부를 본다.
//
// 【정책과 무관하게 유지되는 것】 이메일 재진입 통로(POST /api/auth/email-login)의 생년월일 = **비밀번호 역할**
//   (사장님 SSOT "생년월일은 비번처럼" = 메일+생년월일 2관문). 이는 "수집 요구"가 아니라 로그인 인증 수단이라
//   애플 지침 대상이 아니다 = 그대로 둔다. 단 생년월일 없이 가입한 계정은 이 통로를 쓸 수 없다(소셜로 진입).
export type BirthDatePolicy = "required" | "optional";

export const BIRTHDATE_POLICY: BirthDatePolicy = "optional";

/** 생년월일을 반드시 받아야 하는가 = 화면 게이트·서버 필수검사 공통 판정 1벌 */
export const BIRTHDATE_REQUIRED = BIRTHDATE_POLICY === "required";
